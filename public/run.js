function seededRandom(seed) {
  let value = seed >>> 0;
  return () => {
    value = (value + 0x6d2b79f5) >>> 0;
    let bits = Math.imul(value ^ (value >>> 15), value | 1);
    bits ^= bits + Math.imul(bits ^ (bits >>> 7), bits | 61);
    return ((bits ^ (bits >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle(items, random) {
  for (let i = items.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [items[i], items[j]] = [items[j], items[i]];
  }
  return items;
}

export function createRun(seed, beep = () => {}) {
  const random = seededRandom(seed);
  const quizRandom = seededRandom(seed ^ 0xc3fcaf22);
  const questions = QB.flat();
  const [prompt, choices] = questions[Math.floor(quizRandom() * questions.length)];
  const options = shuffle(choices.map((text, index) => ({ text, index })), quizRandom);
  const quiz = { prompt, options: options.map(option => option.text) };
  const correct = options.findIndex(option => option.index === 0);
  let dist=0,speed=14,lane=0,px=0,py=0,vy=0,slide=0,objs=[],next=14;
  const got=new Set();
  let shield=0,inv=1.2,revives=0,ppeScore=0,toast='',toastT=0,flash=0;
  let nextSur=1500,sur=null,lastSur='',dbl=0,dblAcc=0,tick=0,hitKind=null;

  function spawn(){
   const lanes=shuffle([-1,0,1],random),n=dist>150&&random()<.4?2:1;
   for(let i=0;i<n;i++)objs.push({k:KINDS[random()*KINDS.length|0],l:lanes[i],z:ZMAX});
   if(random()<.75){const fl=lanes[n],t=PPE[random()*5|0],c=3+(random()*3|0);
    for(let i=0;i<c;i++)objs.push({k:'ppe',p:t,l:fl,z:ZMAX-3+i*2.4});}
  }
  const OFFICER=['ใส่ PPE ครบ เยี่ยมมาก! Safety First','เดินในทางเดินเท้านะ ไม่ใช่เลนรถโฟล์คลิฟท์','เจอ Near miss แจ้งได้เลยนะ ไม่ต้องเกรงใจ','วิ่งมาไกลแล้ว อย่าลืมดื่มน้ำนะ','หมวกนิรภัยต้องคาดสายรัดคางด้วยนะ','ทำ KYT ก่อนเริ่มงานทุกครั้งนะ','เก่งมาก! ไม่มีอุบัติเหตุคือเป้าหมายของเรา'];
  function surprise(){
   const ks=['officer','rain','star','double'].filter(k=>k!==lastSur),k=ks[random()*ks.length|0];lastSur=k;beep(660,.1,'triangle');beep(990,.15,'triangle');
   if(k==='officer'){ppeScore+=150;sur={k,t:0,dur:3.4,msg:OFFICER[random()*OFFICER.length|0]}}
   if(k==='rain'){objs=objs.filter(o=>o.k==='ppe'||o.z<12);next=Math.max(next,58);let n=0;
    for(let z=16;z<62;z+=2.4)for(const l of[-1,0,1])objs.push({k:'ppe',p:PPE[n++%5],l,z});
    sur={k,t:0,dur:2.6,msg:'PPE Rain! เก็บให้หมด',sub:'ฝน PPE ตกทั้ง 3 เลน'}}
   if(k==='star'){shield=8;sur={k,t:0,dur:2.6,msg:'Golden Helmet!',sub:'ได้โล่ PPE ฟรี กันชน 1 ครั้ง'}}
   if(k==='double'){dbl=8;sur={k,t:0,dur:2.6,msg:'Safety Week x2!',sub:'คะแนนระยะทาง x2 นาน 8 วินาที'}}
  }
  function update(dt){
   speed=Math.min(34,14+dist/55);const dz=speed*dt;dist+=dz;
   if(dbl>0){dbl-=dt;dblAcc+=dz;while(dblAcc>=1){ppeScore++;dblAcc--}}
   if(sur&&(sur.t+=dt)>sur.dur)sur=null;
   for(const o of objs)o.z-=dz;
   if((next-=dz)<=0){spawn();next=13+random()*9-Math.min(4,dist/500)}
   px+=(lane-px)*Math.min(1,dt*14);
   if(py>0||vy>0){vy-=24*dt;py+=vy*dt;if(py<=0){py=0;vy=0}}
   slide=Math.max(0,slide-dt);inv=Math.max(0,inv-dt);shield=Math.max(0,shield-dt);toastT=Math.max(0,toastT-dt);flash=Math.max(0,flash-dt);
   for(const o of objs){
    if(o.gone||Math.abs(o.z)>.7||Math.abs(o.l-px)>.5)continue;
    if(o.k==='ppe'){o.gone=true;got.add(o.p);ppeScore+=10;beep(880,.07,'triangle');
     if(got.size===5){got.clear();shield=8;toast='FULL PPE! โล่กันชน 1 ครั้ง';toastT=2;beep(1320,.2,'triangle')}continue}
    const t=HZ[o.k].t,hit=t==='block'||(t==='low'&&py<.45)||(t==='high'&&slide<=0);
    if(!hit||inv>0)continue;
    if(shield>0){shield=0;inv=1;o.gone=true;flash=.3;toast='PPE ช่วยไว้! · Saved by PPE';toastT=1.6;beep(300,.2,'triangle');continue}
    hitKind=o.k;return;
   }
   objs=objs.filter(o=>o.z>-3&&!(o.gone&&o.k==='ppe'));
   if(dist>=nextSur){nextSur+=1500;surprise()}
  }


  function input(action) {
    if (hitKind || tick === MAX_TICKS) return false;
    if (action === 'left' || action === 'right') {
      const nextLane = Math.max(-1, Math.min(1, lane + (action === 'left' ? -1 : 1)));
      if (lane === nextLane) return false;
      lane = nextLane;
      beep(380, .04);
    } else if (action === 'up' && py === 0 && vy === 0) {
      vy = 9.2;
      slide = 0;
      beep(520, .06);
    } else if (action === 'down') {
      if (py > 0) vy = -16;
      slide = .7;
      beep(220, .06);
    } else {
      return false;
    }
    return true;
  }

  function answer(index) {
    if (!hitKind || revives || tick === MAX_TICKS || index !== correct) return false;
    revives++;
    objs = objs.filter(o => o.z > 14);
    inv = 2;
    slide = py = vy = 0;
    hitKind = null;
    toast = 'รอดแล้ว! ชนอีกครั้งจบรอบ';
    toastT = 1.8;
    return true;
  }

  return {
    input, answer, quiz, correct,
    get tick() { return tick; },
    get finished() { return !!hitKind || tick === MAX_TICKS; },
    step() {
      if (this.finished) return;
      tick++;
      update(STEP);
    },
    view() {
      return {dist,lane,px,py,vy,slide,objs,got,shield,inv,revives,ppeScore,toast,toastT,flash,sur,dbl,hitKind};
    },
    score() { return Math.floor(dist) + ppeScore; }
  };
}

export function replayScore(seed, ticks, inputs) {
  if (!Number.isInteger(ticks) || ticks < 1 || ticks > MAX_TICKS ||
      !Array.isArray(inputs) || inputs.length > MAX_INPUTS) return null;

  const game = createRun(seed);
  for (const entry of inputs) {
    if (!Array.isArray(entry) || entry.length !== 2) return null;
    const [at, action] = entry;
    if (!Number.isInteger(at) || at < game.tick || at >= ticks) return null;
    while (game.tick < at && !game.finished) game.step();
    if (game.tick !== at) return null;
    const accepted = Number.isInteger(action) ? game.answer(action) : game.input(action);
    if (!accepted) return null;
  }
  while (game.tick < ticks && !game.finished) game.step();
  return game.tick === ticks && game.finished ? game.score() : null;
}
